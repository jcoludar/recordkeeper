def test_assemble_rejects_paperwork_enforcement_without_session_paperwork(tmp_path):
    """Assembling a project that opts into paperwork-enforcement WITHOUT session-paperwork
    fails with a clean diagnostic."""
    import sys
    from pathlib import Path
    ASSEMBLE = Path(__file__).resolve().parent.parent / "tools"
    if str(ASSEMBLE) not in sys.path:
        sys.path.insert(0, str(ASSEMBLE))
    import assemble

    REPO_ROOT = Path(__file__).resolve().parent.parent
    masterbook_root = REPO_ROOT

    project = tmp_path / "proj"
    project.mkdir()
    (project / "CLAUDE.source.md").write_text(
        "---\n"
        "masterbook:\n"
        "  modules: []\n"
        "  substrates: [paperwork-enforcement]\n"
        "  permissions_extra: []\n"
        "  commands: []\n"
        "---\n"
        "body\n"
    )
    with pytest.raises(assemble.SubstrateDependencyError) as exc_info:
        assemble.main(argv=[
            "--masterbook", str(masterbook_root),
            "--source", str(project / "CLAUDE.source.md"),
            "--out", str(project / "CLAUDE.md"),
        ])
    msg = str(exc_info.value)
    assert "paperwork-enforcement" in msg
    assert "session-paperwork" in msg
    assert "requires" in msg.lower()


