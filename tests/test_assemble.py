from assemble import compute_module_hash


def test_hash_stable_across_line_endings(tmp_path):
    p = tmp_path / "m.md"
    p.write_bytes(b"---\nid: x\n---\nbody\n")
    h1 = compute_module_hash(p)
    p.write_bytes(b"---\r\nid: x\r\n---\r\nbody\r\n")
    h2 = compute_module_hash(p)
    assert h1 == h2


def test_hash_changes_on_content_change(tmp_path):
    p = tmp_path / "m.md"
    p.write_text("---\nid: x\n---\nA\n")
    h1 = compute_module_hash(p)
    p.write_text("---\nid: x\n---\nB\n")
    h2 = compute_module_hash(p)
    assert h1 != h2


def test_hash_is_12_hex_chars(tmp_path):
    p = tmp_path / "m.md"
    p.write_text("---\nid: x\n---\nbody\n")
    h = compute_module_hash(p)
    assert len(h) == 12
    assert all(c in "0123456789abcdef" for c in h)


