def test_assemble_with_substrate_end_to_end(tmp_path):
    """Full assembly of a project that opts into store-write-approval.

    Verifies:
      - settings.json has 5 hook entries (3 baseline + 2 substrate).
      - .claude/hooks/ contains all 5 .py files.
      - CLAUDE.md includes the substrate body marker.
      - All deployed hook files are syntactically valid Python.
    """
    import shutil
    src_root = Path(__file__).resolve().parent / "fixtures" / "with_substrate"
    mb_src = src_root / "masterbook"
    proj_src = src_root / "project"
    mb_dst = tmp_path / "mb"
    proj_dst = tmp_path / "proj"
    shutil.copytree(mb_src, mb_dst)
    shutil.copytree(proj_src, proj_dst)

    result = subprocess.run(
        [sys.executable, str(ASSEMBLE), str(mb_dst), str(proj_dst)],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr

    # Settings has all 5 hook entries.
    settings = json.loads((proj_dst / ".claude" / "settings.json").read_text())
    commands = []
    for event_entries in settings.get("hooks", {}).values():
        for entry in event_entries:
            for sub in entry["hooks"]:
                commands.append(sub["command"])
    expected_baseline_basenames = {
        "pre_bash_shell_hygiene.py",
        "pre_tool_use_secrets.py",
        "stop_session_log.py",
    }
    expected_substrate_basenames = {
        "pre_store_write_protection.py",
        "pre_sentinel_no_self_touch.py",
    }
    deployed_basenames = {Path(c).name for c in commands}
    assert expected_baseline_basenames <= deployed_basenames, (
        f"missing baseline hooks; got {deployed_basenames}"
    )
    assert expected_substrate_basenames <= deployed_basenames, (
        f"missing substrate hooks; got {deployed_basenames}"
    )

    # All 5 hook files were copied to .claude/hooks/.
    deployed_dir = proj_dst / ".claude" / "hooks"
    actual_files = {p.name for p in deployed_dir.glob("*.py")}
    assert (expected_baseline_basenames | expected_substrate_basenames) <= actual_files

    # Each deployed hook is syntactically valid Python.
    import ast as _ast
    for p in deployed_dir.glob("*.py"):
        _ast.parse(p.read_text())

    # Substrate body is inlined in CLAUDE.md.
    claude_text = (proj_dst / "CLAUDE.md").read_text()
    assert "Recovery section to verify body inlining" in claude_text


