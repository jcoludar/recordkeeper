from assemble import parse_frontmatter, FrontmatterError


def test_parse_frontmatter_basic():
    text = """---
id: tier-1/example
name: Example
tier: 1
---

body line 1
body line 2
"""
    fm, body = parse_frontmatter(text)
    assert fm["id"] == "tier-1/example"
    assert fm["tier"] == 1
    assert body.strip() == "body line 1\nbody line 2"


def test_parse_frontmatter_missing_raises():
    with pytest.raises(FrontmatterError):
        parse_frontmatter("no frontmatter here\n")


def test_parse_frontmatter_unterminated_raises():
    with pytest.raises(FrontmatterError):
        parse_frontmatter("---\nid: x\n# never closes\n")


